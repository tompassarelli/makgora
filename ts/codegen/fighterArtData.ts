const PRODUCER = "// Generated by ts/codegen/fighterArtData.ts from the roster, looks and clip tables; regenerate instead of editing.";

function flashClips(character: number): number[] {
  const indices = new Set(namedClips(characterClips(character)).map((clip) => clip.index));
  for (const clip of namedClips(characterClips(character))) if (clip.classicStartup !== undefined) indices.add(clip.classicStartup.index);
  for (const clip of contactDamageClips(character) ?? []) indices.add(clip.index);
  const fallback = heroLook(character)?.fallback;
  if (fallback !== undefined) indices.add(fallback.index);
  if (character <= Character.demonHunter) {
    const actions = character === Character.rifleman
      ? [SpecialAction.riflemanBlaster, SpecialAction.riflemanBear, SpecialAction.riflemanTrap, SpecialAction.riflemanRecovery]
      : [SpecialAction.demonHunterEyeBeam, SpecialAction.demonHunterFelRush, SpecialAction.demonHunterWingAscent, SpecialAction.demonHunterImmolate];
    for (const action of actions) for (const grounded of [false, true]) indices.add(specialClip(character, action, grounded, !grounded).index);
    if (character === Character.demonHunter) {
      for (const index of [
        illidan.DEMON_HUNTER_KO_INDEX, illidan.DEMON_HUNTER_LEDGE_CATCH_INDEX,
        illidan.DEMON_HUNTER_SHIELD_BREAK_INDEX, illidan.DEMON_HUNTER_DOWN_WAIT_INDEX,
        illidan.DEMON_HUNTER_GRAB_ESCAPE_INDEX, illidan.DEMON_HUNTER_AIR_DODGE_INDEX,
        illidan.DEMON_HUNTER_JUMP_SQUAT_INDEX, illidan.DEMON_HUNTER_LAND_INDEX,
        illidan.DEMON_HUNTER_LAND_SPECIAL_INDEX, illidan.DEMON_HUNTER_SHIELD_RAISE_INDEX,
        illidan.DEMON_HUNTER_SHIELD_HOLD_INDEX, illidan.DEMON_HUNTER_SHIELD_RELEASE_INDEX,
        illidan.DEMON_HUNTER_RESPAWN_INDEX, illidan.DEMON_HUNTER_LEDGE_JUMP_INDEX,
        illidan.DEMON_HUNTER_TECH_NEUTRAL_INDEX, illidan.DEMON_HUNTER_TECH_FORWARD_INDEX,
        illidan.DEMON_HUNTER_TECH_BACK_INDEX, illidan.DEMON_HUNTER_GET_UP_ROLL_FORWARD_INDEX,
        illidan.DEMON_HUNTER_GET_UP_ROLL_BACK_INDEX, illidan.DEMON_HUNTER_WALK_FORWARD_INDEX,
        illidan.DEMON_HUNTER_RUN_FORWARD_INDEX, illidan.DEMON_HUNTER_INITIAL_DASH_BURST_INDEX,
        illidan.DEMON_HUNTER_TURNAROUND_INDEX, illidan.DEMON_HUNTER_STOP_INDEX,
        illidan.DEMON_HUNTER_CROUCH_INDEX, illidan.DEMON_HUNTER_FAST_FALL_INDEX,
        illidan.DEMON_HUNTER_FALL_INDEX, illidan.DEMON_HUNTER_COMBAT_IDLE_INDEX,
      ]) indices.add(index);
      for (const style of [AttackStyle.forwardSmash, AttackStyle.upSmash, AttackStyle.downSmash]) {
        const clips = illidanSmashClips(style);
        indices.add(clips.charge.index);
        indices.add(clips.release.index);
      }
    }
  }
  const grab = heroLook(character)?.commandGrab;
  if (grab !== undefined) for (const clip of [grab.travel, grab.hold, grab.recovery]) indices.add(clip.index);
  for (const clips of Object.values(heroLook(character)?.followUpClips ?? {})) for (const clip of clips ?? []) indices.add(clip.index);
  return [...indices].sort((a, b) => a - b);
}

const lookModel = (character: number) => HERO_ROSTER.some((hero) => hero.character === character) ? heroLook(character)!.model : undefined;

function wardenBlade(style: AttackStyle): string {
  const move = WARDEN_MOVES.normals[style];
  if (move === undefined) throw new Error(`Warden has no timing for attack style ${style}`);
  const strikes = move.regions.map((region) => region.hit.strike === undefined ? "undefined" : `{ x1: ${region.hit.strike.x1}, z1: ${region.hit.strike.z1}, x2: ${region.hit.strike.x2}, z2: ${region.hit.strike.z2} }`);
  return `{ startupFrames: ${move.startupFrames}, activeFrames: ${move.activeFrames}, strikes: [${strikes.join(", ")}] }`;
}

export function renderFighterArtData(): string {
  const rows = [...fighters].map(([character, { name, source, stock }]) =>
    `  [${character}, { name: ${JSON.stringify(name)}, slug: ${JSON.stringify(fighterSlug(character))}, source: ${JSON.stringify(source)}${stock === undefined ? "" : `, stock: ${JSON.stringify(stock)}`}${lookModel(character) === undefined ? "" : `, model: ${JSON.stringify(lookModel(character))}`} }],`);
  return [
    PRODUCER,
    "// Each fighter's rules live in fighter-art/<slug>.ts, so a change to one fighter's rules invalidates only that fighter's derived art.",
    "export interface FighterArt { readonly name: string; readonly slug: string; readonly source: string; readonly stock?: string; readonly model?: string }",
    "",
    "export interface BladeStrike { readonly x1: number; readonly z1: number; readonly x2: number; readonly z2: number }",
    "",
    "export interface BladeTiming { readonly startupFrames: number; readonly activeFrames: number; readonly strikes: readonly (BladeStrike | undefined)[] }",
    "",
    "export interface FighterRules { readonly victory: string; readonly flashClips: readonly number[]; readonly blade?: Readonly<Record<\"neutralAir\" | \"forwardAir\", BladeTiming>> }",
    "",
    "export const FIGHTER_ART: ReadonlyMap<number, FighterArt> = new Map<number, FighterArt>([",
    ...rows,
    "]);",
    "",
    "export function fighterArt(character: number): FighterArt {",
    "  const art = FIGHTER_ART.get(character);",
    "  if (art === undefined) throw new Error(`no fighter art for character ${character}`);",
    "  return art;",
    "}",
    "",
  ].join("\n");
}

export function renderFighterRules(character: number): string {
  const blade = character === Character.warden
    ? [`  blade: {`, `    neutralAir: ${wardenBlade(AttackStyle.neutralAir)},`, `    forwardAir: ${wardenBlade(AttackStyle.forwardAir)},`, `  },`]
    : [];
  const skins = (heroLook(character)?.costumes ?? []).flatMap((costume, index) => costume.skin === undefined ? [] : [`  { index: ${index}, textures: ${JSON.stringify(costume.skin.textures)} },`]);
  return [
    PRODUCER,
    "import type { FighterRules } from \"../fighterArtData\";",
    "",
    "export const rules: FighterRules = {",
    `  victory: ${JSON.stringify(victoryAnimation(character as Character))},`,
    `  flashClips: [${flashClips(character).join(", ")}],`,
    ...blade,
    "};",
    "",
    ...skins.length === 0 ? [] : [
      "export const costumeSkins: readonly { readonly index: number; readonly textures: Readonly<Record<string, string>> }[] = [",
      ...skins,
      "];",
      "",
    ],
  ].join("\n");
}

export const producers = (): readonly { readonly output: string; readonly render: () => string }[] => [
  { output, render: renderFighterArtData },
  ...[...fighters.keys()].map((character) => ({ output: `${rulesDirectory}/${fighterSlug(character)}.ts`, render: () => renderFighterRules(character) })),
];
