import { BINDING_PRESETS, PRESET_NAMES, keyFor, keyLabel, presetBindings } from "../src/game/input/keyBindings";
import { GUIDE_INTRO, GUIDE_SECTIONS, type GuideSection } from "../src/game/ui/guide/docs";
import { CONTROL_ROWS, HOW_TO_PLAY_POINTS, HOW_TO_PLAY_TITLE, ITEM_RULE_HELP, MODES, PLAYER_COMMANDS, TRAINING_RULE_HELP } from "../src/game/ui/guide/text";
import { LESSONS } from "../src/game/match/tutorial";
import { Action } from "../src/game/input/actions";

export const markdownOutput = "../docs/player-guide.md";
export const bbcodeOutput = "../docs/player-guide.bbcode.txt";

const PRODUCER = "Generated by ts/codegen/playerGuide.ts from ts/src/game/ui/guide/ (`bun run generate` in ts/); edit the source there, never this file.";

const unique = (values: readonly string[]): string[] => values.filter((value, at) => values.indexOf(value) === at);
const lessonKey = (action: Action): string => keyLabel(keyFor(presetBindings("wasd"), action, 0));

const extraSections = (): GuideSection[] => [
  { title: "Modes", paragraphs: Object.values(MODES) },
  { title: HOW_TO_PLAY_TITLE, paragraphs: HOW_TO_PLAY_POINTS },
  { title: "Training settings", paragraphs: unique([...Object.values(TRAINING_RULE_HELP), ...Object.values(ITEM_RULE_HELP)]) },
  { title: "Tutorial lessons (keys shown for WASD)", paragraphs: LESSONS.map(({ name, instruction }) => `${name}: ${instruction(lessonKey)}`) },
  { title: "Commands", paragraphs: PLAYER_COMMANDS },
];

const controlsTable = (): string[] => [
  `| Action | ${BINDING_PRESETS.map((preset) => PRESET_NAMES[preset]).join(" | ")} |`,
  `| --- | ${BINDING_PRESETS.map(() => "---").join(" | ")} |`,
  ...CONTROL_ROWS.map(([name, action]) => `| ${name} | ${BINDING_PRESETS.map((preset) => keyLabel(keyFor(presetBindings(preset), action, 0))).join(" | ")} |`),
];

const sections = (): GuideSection[] => [...GUIDE_SECTIONS, ...extraSections()];

export function renderMarkdown(): string {
  const lines = [`<!-- ${PRODUCER} -->`, "", "# Player guide", "", ...GUIDE_INTRO.flatMap((text) => [text, ""]), "## Keyboard controls", "", "WASD is the default layout. Change it on the Controls screen (F2 at fighter select).", "", ...controlsTable(), ""];
  for (const { title, paragraphs } of sections()) lines.push(`## ${title}`, "", ...paragraphs.flatMap((text) => [text, ""]));
  return `${lines.join("\n").trimEnd()}\n`;
}

const bb = (text: string): string => text.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_, label: string, url: string) => `[URL=${url.startsWith("http") ? url : `https://github.com/tompassarelli/makgora/blob/main/docs/${url}`}]${label}[/URL]`).replace(/`([^`]+)`/g, "$1");

export function renderBbcode(): string {
  const lines = [PRODUCER, "", "[SIZE=5][B]Player guide[/B][/SIZE]", "", ...GUIDE_INTRO.flatMap((text) => [bb(text), ""]), "[B]Keyboard controls[/B]", "[TABLE]",
    `[TR][TD][B]Action[/B][/TD]${BINDING_PRESETS.map((preset) => `[TD][B]${PRESET_NAMES[preset]}[/B][/TD]`).join("")}[/TR]`,
    ...CONTROL_ROWS.map(([name, action]) => `[TR][TD]${name}[/TD]${BINDING_PRESETS.map((preset) => `[TD]${keyLabel(keyFor(presetBindings(preset), action, 0))}[/TD]`).join("")}[/TR]`), "[/TABLE]", ""];
  for (const { title, paragraphs } of sections()) lines.push(`[B]${title}[/B]`, "", ...paragraphs.flatMap((text) => [bb(text), ""]));
  return `${lines.join("\n").trimEnd()}\n`;
}
