import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { tsRoot } from "./sync";

export const output = "src/generated/strikes/heroStrikeMomentInfo.ts";
export const fightersDirectory = join(tsRoot, "src/game/fighters");

const HEADER = "// Generated by ts/codegen/strikeIndex.ts from the fighters' strikeMoments.ts modules; regenerate instead of editing.";
const EXPORT = /^export const (\w+)StrikeMoments\b/m;

interface StrikeModule { readonly folder: string; readonly key: string }

const strikeModules = (directory: string): StrikeModule[] =>
  readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(directory, entry.name, "strikeMoments.ts")))
    .map((entry) => {
      const key = EXPORT.exec(readFileSync(join(directory, entry.name, "strikeMoments.ts"), "utf8"))?.[1];
      if (key === undefined) throw new Error(`${entry.name}/strikeMoments.ts exports no <character>StrikeMoments table`);
      return { folder: entry.name, key };
    })
    .sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));

export const renderStrikeIndex = (directory: string = fightersDirectory): string => {
  const modules = strikeModules(directory);
  return [
    HEADER,
    'import { Character } from "../../game/sim/codes";',
    ...modules.map(({ folder, key }) => `import { ${key}StrikeMoments } from "../../game/fighters/${folder}/strikeMoments";`),
    "",
    "/**",
    " * Per hero and attack style (or SPECIAL_KEY plus a special slot): the clip measured, the clip",
    " * seconds where it reaches farthest toward its strike and the sequence's length.",
    " */",
    "export const HERO_STRIKE_MOMENTS: { readonly [character: number]: { readonly [style: number]: { readonly clip: number; readonly seconds: number; readonly end: number } | undefined } | undefined } = {",
    ...modules.map(({ key }) => `  [Character.${key}]: ${key}StrikeMoments,`),
    "};",
    "",
  ].join("\n");
};
