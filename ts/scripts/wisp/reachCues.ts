import { AttackPhase, AttackStyle, Character } from "../../src/game/sim/codes";
import { createFighter } from "../../src/game/sim/fighter";
import { authoredHitRegionCount } from "../../src/game/sim/hitRegions";
import { type DrawnModel } from "./drawnModel";
import { sampleAttack } from "./hurtboxView";


export const BODY_HEIGHT = 132.0;

export const REACH_MARGIN = 0.15;

const AERIAL_STYLES: readonly AttackStyle[] = [AttackStyle.neutralAir, AttackStyle.forwardAir, AttackStyle.backAir, AttackStyle.upAir, AttackStyle.downAir];

export interface ReachCueRow {
  readonly character: Character;
  readonly style: AttackStyle;
  readonly beyond: number;
}


export function measuredStyles(character: Character): AttackStyle[] {
  const fighter = createFighter(character, 0.0, 1);
  return Object.values(AttackStyle).filter((style) => {
    if (style === AttackStyle.shot || style === AttackStyle.grab) return false;
    if (style === AttackStyle.demonHunterDashAttack && character !== Character.demonHunter) return false;
    if (style === AttackStyle.dashAttack && fighter.tuning.moves?.dashAttack !== style) return false;
    if ((style === AttackStyle.jab2 || style === AttackStyle.jab3) && fighter.tuning.moves?.normals[style] === undefined) return false;
    return authoredHitRegionCount(style, fighter.tuning.moves) > 0;
  });
}


function drawnTriangles(model: DrawnModel, clip: number, seconds: number): Float32Array {
  try {
    return model.triangles(clip, seconds, 1);
  } catch {
    return model.triangles(0, 0.0, 1);
  }
}


export function measureReachCue(model: DrawnModel, character: Character, style: AttackStyle): ReachCueRow {
  const frames = sampleAttack(character, style, 1, AERIAL_STYLES.includes(style));
  let bodyMinX = Infinity, bodyMaxX = -Infinity, bodyMinZ = Infinity, bodyMaxZ = -Infinity;
  const hits: { minX: number; maxX: number; minZ: number; maxZ: number }[] = [];
  for (const frame of frames) {
    if (frame.phase !== AttackPhase.active || frame.clip === undefined) continue;
    if (frame.strikes.length === 0) continue;
    for (const strike of frame.strikes) {
      const x1 = strike.x1 - frame.x, x2 = strike.x2 - frame.x, z1 = strike.z1 - frame.z, z2 = strike.z2 - frame.z;
      hits.push({ minX: Math.min(x1, x2) - strike.radius, maxX: Math.max(x1, x2) + strike.radius, minZ: Math.min(z1, z2) - strike.radius, maxZ: Math.max(z1, z2) + strike.radius });
    }
    const triangles = drawnTriangles(model, frame.clip, frame.seconds);
    for (let i = 0; i < triangles.length; i += 2) {
      bodyMinX = Math.min(bodyMinX, triangles[i] ?? 0);
      bodyMaxX = Math.max(bodyMaxX, triangles[i] ?? 0);
      bodyMinZ = Math.min(bodyMinZ, triangles[i + 1] ?? 0);
      bodyMaxZ = Math.max(bodyMaxZ, triangles[i + 1] ?? 0);
    }
  }
  let beyond = -Infinity;
  for (const hit of hits) beyond = Math.max(beyond, hit.maxX - bodyMaxX, bodyMinX - hit.minX, hit.maxZ - bodyMaxZ, bodyMinZ - hit.minZ);
  return { character, style, beyond: hits.length === 0 ? -Infinity : beyond };
}


export const showsReachCue = (row: ReachCueRow): boolean => row.beyond > REACH_MARGIN * BODY_HEIGHT;


export function reachCueSource(rows: readonly ReachCueRow[]): string {
  const characters = [...new Set(rows.map((row) => row.character))].sort((a, b) => a - b);
  return [
    "// Generated by `bun wisp view reachcues --assets DIR` from the drawn Classic fighter models; regenerate instead of editing.",
    "import type { AttackStyle } from \"../sim/codes\";",
    "",
    `export const REACH_CUE_NORMALS: { readonly [character: number]: readonly AttackStyle[] | undefined } = {`,
    ...characters.map((character) => `  ${character}: [${rows.filter((row) => row.character === character && showsReachCue(row)).map((row) => row.style).join(", ")}],`),
    "};",
    "",
  ].join("\n");
}
