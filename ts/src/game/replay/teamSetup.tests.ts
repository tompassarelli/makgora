import { assertEquals, assertTrue, test } from "wisp/src/runtime/testing";
import { PARTICIPANT_SLOTS } from "../input/participants";
import { createFighter } from "../sim/fighter";
import { configureMatchTeams, initializeMatchFighters } from "../match/step";
import { type Team } from "../sim/teams";
import { Phase, resolveStocks, setParticipants, winningMask } from "../lobby/lobbyState";
import { stateChecksum } from "./canonical";
import { firstStateDifference } from "./difference";
import { copyReplayState, createReplaySnapshot } from "./snapshot";


test("team setup and a seeded 2v2 result retain every team and friendly fire field through rollback [k1 scenario]", () => {
  const live = createReplaySnapshot();
  const saved = createReplaySnapshot();
  const game = live.match;
  setParticipants(game, 3, 12);
  game.teamBattle = true;
  game.friendlyFire = true;
  const choices: readonly Team[] = [2, 3, 2, 3];
  for (const slot of PARTICIPANT_SLOTS) {
    game.teamChoices[slot] = choices[slot] ?? 0;
    live.world.fighters[slot] = createFighter(game.characterChoices[slot], 0.0, 1);
  }
  live.world.mask = 15;
  game.phase = Phase.match;
  initializeMatchFighters(game, live.world);
  copyReplayState(saved, live);
  assertEquals(saved.match.teamBattle, true);
  assertEquals(saved.match.friendlyFire, true);
  for (const slot of PARTICIPANT_SLOTS) assertEquals(saved.match.teamChoices[slot], choices[slot]);
  const checksum = stateChecksum(saved);
  game.teamBattle = false;
  game.friendlyFire = false;
  game.teamChoices.fill(0);
  configureMatchTeams(game, live.world);
  assertTrue(stateChecksum(live) !== checksum);
  copyReplayState(live, saved);
  assertEquals(firstStateDifference(saved, live), undefined);
  assertEquals(stateChecksum(live), checksum);
  assertEquals(game.teamBattle, true);
  assertEquals(game.friendlyFire, true);
  for (const slot of PARTICIPANT_SLOTS) assertEquals(game.teamChoices[slot], choices[slot]);
  assertEquals(live.world.teamBattle, true);
  assertEquals(live.world.friendlyFire, true);
  for (const slot of PARTICIPANT_SLOTS) assertEquals(live.world.teamChoices[slot], choices[slot]);
  game.friendlyFire = false;
  assertEquals(firstStateDifference(saved, live), "match.friendlyFire");
  assertTrue(stateChecksum(live) !== checksum);
  copyReplayState(live, saved);
  game.teamChoices[1] = 0;
  assertEquals(firstStateDifference(saved, live), "match.slot1.team");
  assertTrue(stateChecksum(live) !== checksum);
  copyReplayState(live, saved);
  const second = live.world.fighters[1];
  const fourth = live.world.fighters[3];
  if (second === undefined || fourth === undefined) throw new Error("missing team fighter");
  second.status.stocks = 0; fourth.status.stocks = 0;
  resolveStocks(game, live.world);
  assertEquals(winningMask(game), 5);
  copyReplayState(saved, live);
  copyReplayState(live, saved);
  assertEquals(winningMask(live.match), 5);
  assertEquals(firstStateDifference(saved, live), undefined);
});
