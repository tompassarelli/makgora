import { existsSync, mkdirSync, readdirSync } from 'node:fs';
import { unlink } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { Effect } from 'effect';
import { encodeVerified, hash, parseSource } from './original-clips';
import { type CostumeSkin, skinnedBody } from './costume-skin';
import { modelFacts } from '../../ts/node_modules/wisp/host/models/models';
import { replaceModelFacts, writeGenerated } from '../../ts/scripts/wisp/modelFactsTable';
import { readClipRecords, writeClipRecord } from '../../ts/scripts/clipEvidence';
import { FIGHTER_ART, fighterArt } from '../../ts/src/generated/fighterArtData';

const PRODUCER = '// Generated by tools/animations/costume-bodies.ts from each fighter\'s timeline body and costume skins; regenerate instead of editing.';
const COSTUMES = resolve(import.meta.dir, '../../ts/src/generated/costumes');
const INDEX = join(COSTUMES, 'costumeBodies.ts');
const RULES = resolve(import.meta.dir, '../../ts/src/generated/fighter-art');

const [poolArg, fighterName] = process.argv.slice(2);
if (poolArg === undefined || fighterName === undefined) throw new Error('usage: bun tools/animations/costume-bodies.ts PRIVATE_POOL FIGHTER');
const pool = resolve(poolArg);
if (!relative(resolve(import.meta.dir, '../..'), pool).startsWith('..')) throw new Error('Costume bodies stay in private storage');
const character = [...FIGHTER_ART].find(([, fighter]) => fighter.name === fighterName)?.[0];
if (character === undefined) throw new Error(`Unknown fighter ${fighterName}`);
const fighter = fighterArt(character);

// Loaded by path, not imported, so this step's key covers only its own fighter's rules (ts/scripts/wisp/fighterArt.ts).
const skins = ((require(join(RULES, `${fighter.slug}.ts`)) as { readonly costumeSkins?: readonly CostumeSkin[] }).costumeSkins ?? []);
const prefix = `${fighter.name}CostumeBody`;
const shard = join(COSTUMES, `${fighter.slug}.ts`);
const identifier = (slug: string) => slug.replace(/[^A-Za-z0-9]+(.)?/g, (_, next: string | undefined) => next?.toUpperCase() ?? '');

function indexSource(): string {
    const slugs = existsSync(COSTUMES) ? readdirSync(COSTUMES).filter(file => file.endsWith('.ts') && file !== 'costumeBodies.ts').map(file => file.slice(0, -3)).sort() : [];
    const characters = new Map([...FIGHTER_ART].map(([id, art]) => [art.slug, id]));
    return [PRODUCER,
        '// A costume body is its fighter\'s timeline body in a costume\'s skin, on the same timeline, so it plays every clip at the clip\'s own times.',
        ...slugs.map(slug => `import * as ${identifier(slug)} from "./${slug}";`),
        '',
        'const FIGHTERS: Readonly<Record<number, { readonly bodies: Readonly<Record<number, string>> }>> = {',
        ...slugs.map(slug => `  ${characters.get(slug)}: ${identifier(slug)},`),
        '};',
        '',
        '/** The model that draws this fighter\'s timeline clips in this costume, if the costume has its own body. */',
        'export function costumeBody(character: number, costume: number): string | undefined {',
        '  return FIGHTERS[character]?.bodies[costume];',
        '}',
        ''].join('\n');
}

await Effect.runPromise(Effect.tryPromise({ try: async () => {
    const record = readClipRecords(pool).find((entry: { fighter: string }) => entry.fighter === fighter.name);
    if (record === undefined) throw new Error(`No original clips for ${fighter.name}`);
    const directory = join(pool, 'imports/war3mapImported');
    const timeline: string[] = [...new Set<string>(record.clips.filter((clip: { timeline?: boolean }) => clip.timeline === true).map((clip: { filename: string }) => clip.filename))];
    if (skins.length > 0 && timeline.length !== 1) throw new Error(`${fighter.name}: a costume skin needs one timeline body, found ${timeline.length}`);
    const costumes: { index: number; filename: string; modelPath: string; sha256: string; bytes: number }[] = [];
    const facts: Record<string, ReturnType<typeof modelFacts>> = {};
    if (skins.length > 0) {
        const body = parseSource(await Bun.file(join(directory, timeline[0]!)).arrayBuffer());
        for (const skin of skins) {
            const bytes = encodeVerified(skinnedBody(body, skin)), sha256 = hash(bytes);
            const filename = `${prefix}${skin.index}-${sha256}.mdx`, modelPath = `war3mapImported\\${filename}`;
            await Bun.write(join(directory, filename), bytes);
            costumes.push({ index: skin.index, filename, modelPath, sha256, bytes: bytes.byteLength });
            facts[modelPath] = modelFacts(new Uint8Array(bytes));
            console.log(`${fighter.name} costume ${skin.index}: ${bytes.byteLength} bytes, ${Object.keys(skin.textures).length} texture swaps on ${timeline[0]}`);
        }
    }
    const kept = new Set(costumes.map(costume => costume.filename));
    if (existsSync(directory)) for (const file of readdirSync(directory)) if (file.startsWith(prefix) && !kept.has(file)) await unlink(join(directory, file));
    if (costumes.length > 0) record.costumes = costumes; else delete record.costumes;
    writeClipRecord(pool, record);
    replaceModelFacts([`war3mapImported\\${prefix}`], facts);
    const hadShard = existsSync(shard);
    if (costumes.length > 0) mkdirSync(COSTUMES, { recursive: true });
    if (costumes.length > 0) writeGenerated(shard, [PRODUCER, '', 'export const bodies: Readonly<Record<number, string>> = {', ...costumes.map(costume => `  ${costume.index}: ${JSON.stringify(costume.modelPath)},`), '};', ''].join('\n'));
    else if (hadShard) await unlink(shard);
    if (costumes.length > 0 || hadShard) writeGenerated(INDEX, indexSource());
    console.log(`${fighter.name}: ${costumes.length} costume bodies`);
}, catch: cause => new Error('Costume body export failed', { cause }) }));
