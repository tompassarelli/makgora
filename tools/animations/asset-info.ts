


interface ClipBinding {

  readonly key: string;
  readonly index: number;

  readonly seconds?: number;
}

export interface ModelAssetInfo {

  readonly prefix: string;
  readonly modelPath: string;
  readonly clips: readonly ClipBinding[];
}


export function seconds(value: number): string {
  if (Number.isInteger(value)) return value.toFixed(1);
  if (Math.fround(value) !== value) return `f32(${value})`;
  const shortest = [...Array(9).keys()].map((digits) => Number(value.toPrecision(digits + 1))).find((decimal) => Math.fround(decimal) === value) ?? value;
  return shortest === value ? String(value) : `f32(${shortest})`;
}

export function typescriptAssetInfo(generator: string, models: readonly ModelAssetInfo[]): string {
  const lines = [
    `// Generated by ${generator} from the authored models; regenerate instead of editing.`,
    'import { f32 } from "wisp/src/sim/f32";',
    "",
  ];
  for (const { prefix, modelPath, clips } of models) {
    lines.push(`export const ${prefix}_MODEL_FILE = ${JSON.stringify(modelPath)};`);
    for (const clip of clips) {
      lines.push(`export const ${prefix}_${clip.key}_INDEX = ${clip.index};`);
      if (clip.seconds !== undefined) lines.push(`export const ${prefix}_${clip.key}_SECONDS = ${seconds(clip.seconds)};`);
    }
  }
  return `${lines.join("\n")}\n`;
}
