import { parseMDL, generateMDX, parseMDX } from "../animations/node_modules/war3-model";
import { join } from "node:path";

const output = join(import.meta.dir, "../../build/impact-assets");
const hash = (bytes: Uint8Array) => new Bun.CryptoHasher("sha256").update(bytes).digest("hex");
type Rgb = [number, number, number];
const flames: [string, Rgb, Rgb, Rgb][] = [
    ["Red", [1, .78, .55], [1, .3, .12], [.55, .06, .02]],
    ["Blue", [.72, .86, 1], [.22, .48, 1], [.05, .12, .55]],
    ["Green", [.76, 1, .66], [.26, .92, .26], [.04, .5, .08]],
];
const size = 64;
const texture = new Uint8Array(18 + size * size * 4);
texture[2] = 2; texture[12] = size; texture[14] = size; texture[16] = 32; texture[17] = 0x28;
for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const u = (x + .5) * 2 / size - 1, v = 1 - (y + .5) * 2 / size;
    const half = .62 * Math.sqrt(Math.max(0, (1 - v) / 2)) + .06;
    const r = Math.hypot(u / half, v);
    const alpha = Math.max(0, 1 - r * r) ** 1.6;
    texture.set([255, 255, 255, Math.round(alpha * 255)], 18 + (y * size + x) * 4);
}
const textureName = `CandleFlame-${hash(texture)}.tga`;
const bgr = ([r, g, b]: Rgb) => `{ ${b}, ${g}, ${r} }`;
const extent = "MinimumExtent { -8, -8, 0 }, MaximumExtent { 8, 8, 24 }, BoundsRadius 16,";
const imports = [textureName];
const assetInfo: string[] = [];
for (const [name, core, body, tip] of flames) {
    const mdl = `Version { FormatVersion 800, }
        Model "Smashcraft Candle Flame ${name}" { BlendTime 0, ${extent} }
        Sequences 1 { Anim "Stand" { Interval { 0, 1000 }, ${extent} } }
        Textures 1 { Bitmap { Image "war3mapImported\\${textureName}", } }
        ParticleEmitter2 "Flame" {
            ObjectId 0, Unshaded, Unfogged, ModelSpace,
            static Speed 34, static Variation 0.15, static Latitude 4,
            static Gravity 0, static EmissionRate 40,
            static Width 2, static Length 2,
            LifeSpan 0.42, Blend, Rows 1, Columns 1, Head,
            TailLength 0, Time 0.35,
            SegmentColor { Color ${bgr(core)}, Color ${bgr(body)}, Color ${bgr(tip)}, }
            Alpha { 230, 170, 0 }, ParticleScaling { 7, 5, 1.5 },
            LifeSpanUVAnim { 0, 0, 1 }, DecayUVAnim { 0, 0, 1 },
            TailUVAnim { 0, 0, 1 }, TailDecayUVAnim { 0, 0, 1 },
            TextureID 0, ReplaceableId 0, PriorityPlane 0,
        }
        PivotPoints 1 { { 0, 0, 0 }, }`;
    const bytes = new Uint8Array(generateMDX(parseMDL(mdl)));
    const decoded = parseMDX(bytes.buffer);
    const emitter = decoded.ParticleEmitters2[0];
    if (decoded.ParticleEmitters2.length !== 1 || emitter === undefined) throw new Error(`${name}: lost the flame emitter`);
    if ((emitter.Flags & 0x80000) === 0) throw new Error(`${name}: flame particles must stay in model space so a moving candle leaves no trail`);
    const middle = Array.from(emitter.SegmentColor?.[1] ?? []);
    if (middle.join() !== body.map(Math.fround).join()) throw new Error(`${name}: flame colour ${middle} lost its ${body} body`);
    const modelName = `CandleFlame${name}-${hash(bytes)}.mdx`;
    await Bun.write(join(output, modelName), bytes);
    await Bun.write(join(output, `CandleFlame${name}.mdl`), mdl);
    imports.push(modelName);
    assetInfo.push(`export const CANDLE_FLAME_${name.toUpperCase()}_MODEL = ${JSON.stringify(`war3mapImported\\${modelName}`)};`);
}
await Bun.write(join(output, textureName), texture);
await Bun.write(join(import.meta.dir, "../../ts/src/generated/assets/candleAssetInfo.ts"),
    `// Generated by tools/effects/candle.ts from the authored candle flames; regenerate instead of editing.\n${assetInfo.join("\n")}\n`);
await Bun.write(join(output, "candle-imports.txt"), imports.join("\n") + "\n");
console.log("Three original candle flames (red, blue, green): one model-space emitter each; MDX roundtrip colour checks passed.");
